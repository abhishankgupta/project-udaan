-- media module. Photos are stored in Postgres for the pilot (small, re-encoded JPEGs);
-- the storage interface lets them move to S3-compatible storage (Cloudflare R2) later.
CREATE TABLE media_objects (
    id            UUID PRIMARY KEY,
    owner_id      UUID        NOT NULL REFERENCES users (id),
    content_type  VARCHAR(64) NOT NULL,
    size_bytes    INT         NOT NULL,
    width         INT         NOT NULL,
    height        INT         NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX media_objects_owner_idx ON media_objects (owner_id, created_at DESC);

CREATE TABLE media_blobs (
    media_id  UUID PRIMARY KEY REFERENCES media_objects (id) ON DELETE CASCADE,
    bytes     BYTEA NOT NULL
);

-- problem module.
CREATE SEQUENCE problem_code_seq START 1;

CREATE TABLE problems (
    id                UUID PRIMARY KEY,
    public_code       VARCHAR(24)  NOT NULL UNIQUE,
    title             VARCHAR(150) NOT NULL,
    description       TEXT         NOT NULL,
    category_id       UUID         NOT NULL REFERENCES categories (id),
    submitter_id      UUID         NOT NULL REFERENCES users (id),
    state_id          INT          NOT NULL REFERENCES states (id),
    city_id           INT          NOT NULL REFERENCES cities (id),
    locality_id       INT          REFERENCES localities (id),
    locality_text     VARCHAR(120),
    address_text      VARCHAR(200),
    latitude          DOUBLE PRECISION,
    longitude         DOUBLE PRECISION,
    urgency           VARCHAR(16)  NOT NULL,
    people_affected   INT,
    estimated_impact  VARCHAR(500),
    desired_outcome   VARCHAR(500) NOT NULL,
    assistance_types  VARCHAR(200) NOT NULL,
    status            VARCHAR(32)  NOT NULL,
    is_anonymous      BOOLEAN      NOT NULL DEFAULT FALSE,
    support_count     INT          NOT NULL DEFAULT 0,
    solution_count    INT          NOT NULL DEFAULT 0,
    comment_count     INT          NOT NULL DEFAULT 0,
    follower_count    INT          NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0
);
CREATE INDEX problems_submitter_idx ON problems (submitter_id, created_at DESC);
CREATE INDEX problems_city_status_idx ON problems (city_id, status, created_at DESC);

CREATE TABLE problem_media (
    problem_id  UUID NOT NULL REFERENCES problems (id) ON DELETE CASCADE,
    media_id    UUID NOT NULL REFERENCES media_objects (id),
    sort_order  INT  NOT NULL,
    PRIMARY KEY (problem_id, sort_order)
);

CREATE TABLE problem_updates (
    id           UUID PRIMARY KEY,
    problem_id   UUID        NOT NULL REFERENCES problems (id) ON DELETE CASCADE,
    author_id    UUID        REFERENCES users (id),
    type         VARCHAR(32) NOT NULL,
    from_status  VARCHAR(32),
    to_status    VARCHAR(32),
    body         VARCHAR(2000),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX problem_updates_problem_idx ON problem_updates (problem_id, created_at);
